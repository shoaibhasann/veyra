/** The desks, lon/lat. */
const HUBS: [number, number, string][] = [
  [103.82, 1.35, "Singapore"],
  [101.69, 3.14, "Kuala Lumpur"],
  [151.21, -33.87, "Sydney"],
  [144.96, -37.81, "Melbourne"],
  [174.76, -36.85, "Auckland"],
];

const cellX = (lon: number) => ((lon + 180) / 360) * W;
const cellY = (lat: number) => ((LAT_TOP - lat) / (LAT_TOP - LAT_BOT)) * H;

export default function DotMap({ className = "" }: { className?: string }) {
  const dots: string[] = [];
  for (let y = 0; y < H; y++) {
    const row = MASK[y];
    for (let x = 0; x < W; x++) {
      if (row[x] === "1") dots.push(`M${x + 0.5} ${y + 0.5}h0`);
    }
  }
  return (
    <svg
      viewBox={`0 0 ${W} ${H}`}
      className={`block w-full ${className}`}
      aria-hidden="true"
      focusable="false"
    >
      {/* One path, every dot: round caps turn zero-length segments into
          circles, and a single node keeps the DOM flat. */}
      <path
        d={dots.join("")}
        stroke="rgba(17, 17, 17, 0.32)"
        strokeWidth={0.62}
        strokeLinecap="round"
        fill="none"
      />
      {HUBS.map(([lon, lat, name]) => (
        <circle
          key={name}
          cx={cellX(lon)}
          cy={cellY(lat)}
          r={0.85}
          fill="var(--color-beam)"
        >
          <title>{name}</title>
        </circle>
      ))}
    </svg>
  );
}
